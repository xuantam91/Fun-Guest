/**
 * Generate 2,000 distinct English questions for vocabulary OR communication topics.
 * @param {string} level 
 * @param {number} targetCount 
 */
export function generateEnglishQuestions(level, targetCount = 2000) {
  const questions = []
  const seen = new Set()

  // 1. If it's one of the 20 Communication topics:
  if (englishCommunicationConcepts[level]) {
    const conceptList = englishCommunicationConcepts[level]
    let attempts = 0

    while (questions.length < targetCount && attempts < targetCount * 30) {
      attempts++
      const item = conceptList[Math.floor(Math.random() * conceptList.length)]
      const pattern = Math.floor(Math.random() * 4)

      let qText = ''
      let correct = ''
      let exp = ''

      if (pattern === 0) {
        qText = `Trong tiếng Anh, từ/câu "${item.en}" dịch sang tiếng Việt nghĩa là gì?`
        correct = item.vn
        exp = `"${item.en}" dịch sang tiếng Việt chính xác là "${item.vn}".`
      } else if (pattern === 1) {
        qText = `Để diễn đạt ý "${item.vn}" bằng tiếng Anh, bé chọn câu nào?`
        correct = item.en
        exp = `Ý nghĩa "${item.vn}" được phát biểu bằng tiếng Anh là "${item.en}".`
      } else if (pattern === 2) {
        qText = `Tình huống: ${item.scenario}. Bé nên dùng từ/câu nào?`
        correct = item.en
        exp = `Trong tình huống ${item.scenario}, câu phù hợp nhất là "${item.en}".`
      } else {
        qText = `Chọn từ/câu tiếng Anh tương ứng với nghĩa: "${item.vn}"`
        correct = item.en
        exp = `"${item.en}" tương ứng hoàn toàn với nghĩa "${item.vn}".`
      }

      const isLeft = Math.random() < 0.5
      const distractor = item.dist[Math.floor(Math.random() * item.dist.length)]

      const leftVal = isLeft ? correct : distractor
      const rightVal = isLeft ? distractor : correct

      const hashKey = `${qText.trim().toLowerCase()}_${leftVal.trim().toLowerCase()}_${rightVal.trim().toLowerCase()}`
      if (!seen.has(hashKey)) {
        seen.add(hashKey)
        questions.push({
          question: qText,
          option_left: leftVal,
          option_right: rightVal,
          correct_option: isLeft ? 'left' : 'right',
          explanation: exp
        })
      }
    }
    return questions
  }

  // 2. Otherwise: Vocabulary Banks (Starters, Movers, Flyers, A1, A2, B1, B2)
  const bank = englishVocabulary[level] || englishVocabulary['starters']
  let attempts = 0

  while (questions.length < targetCount && attempts < targetCount * 35) {
    attempts++
    const targetItem = bank[Math.floor(Math.random() * bank.length)]
    
    // Pick distractor from same bank
    let distractorItem = bank[Math.floor(Math.random() * bank.length)]
    while (distractorItem.word === targetItem.word && bank.length > 1) {
      distractorItem = bank[Math.floor(Math.random() * bank.length)]
    }

    const type = Math.floor(Math.random() * 3)
    let qText = ''
    let leftVal = ''
    let rightVal = ''
    let correct = 'left'
    let exp = ''

    const isLeft = Math.random() < 0.5

    if (type === 0) {
      qText = `Từ tiếng Anh "${targetItem.word}" có nghĩa tiếng Việt là gì?`
      leftVal = isLeft ? targetItem.vn : distractorItem.vn
      rightVal = isLeft ? distractorItem.vn : targetItem.vn
      correct = isLeft ? 'left' : 'right'
      exp = `"${targetItem.word}" dịch sang tiếng Việt có nghĩa là "${targetItem.vn}".`
    } else if (type === 1) {
      qText = `Từ nào trong tiếng Anh có nghĩa là "${targetItem.vn}"?`
      leftVal = isLeft ? targetItem.word : distractorItem.word
      rightVal = isLeft ? distractorItem.word : targetItem.word
      correct = isLeft ? 'left' : 'right'
      exp = `"${targetItem.vn}" trong tiếng Anh là từ "${targetItem.word}".`
    } else {
      qText = `Bé hãy chọn cặp từ tiếng Anh - Việt chính xác cho "${targetItem.word}":`
      leftVal = isLeft ? `${targetItem.word} = ${targetItem.vn}` : `${targetItem.word} = ${distractorItem.vn}`
      rightVal = isLeft ? `${targetItem.word} = ${distractorItem.vn}` : `${targetItem.word} = ${targetItem.vn}`
      correct = isLeft ? 'left' : 'right'
      exp = `Cặp từ chính xác là "${targetItem.word} = ${targetItem.vn}".`
    }

    const hashKey = `${qText.trim().toLowerCase()}_${leftVal.trim().toLowerCase()}_${rightVal.trim().toLowerCase()}`
    if (!seen.has(hashKey)) {
      seen.add(hashKey)
      questions.push({
        question: qText,
        option_left: leftVal,
        option_right: rightVal,
        correct_option: correct,
        explanation: exp
      })
    }
  }

  return questions
}
